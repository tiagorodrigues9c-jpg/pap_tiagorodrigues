create sequence if not exists public.municipal_occurrence_code_seq start 148;
create sequence if not exists public.municipal_request_code_seq start 317;

create table if not exists public.municipal_occurrences (
  id bigint generated by default as identity primary key,
  code text not null unique default ('VN-' || to_char(now(), 'YYYY') || '-' || lpad(nextval('municipal_occurrence_code_seq')::text, 4, '0')),
  reporter_id uuid references auth.users(id) on delete set null,
  category text not null check (category in ('Iluminação pública', 'Buraco na via', 'Limpeza urbana', 'Espaços verdes', 'Outro')),
  description text not null,
  location text not null,
  latitude numeric(9,6),
  longitude numeric(9,6),
  photo_path text,
  status text not null default 'Em análise' check (status in ('Em análise', 'Em execução', 'Resolvida', 'Rejeitada')),
  department text,
  resolution_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.municipal_requests (
  id bigint generated by default as identity primary key,
  code text not null unique default ('REQ-' || to_char(now(), 'YYYY') || '-' || lpad(nextval('municipal_request_code_seq')::text, 4, '0')),
  requester_id uuid not null references auth.users(id) on delete cascade,
  service_type text not null,
  notes text,
  status text not null default 'Recebido' check (status in ('Recebido', 'Em análise', 'A aguardar documentos', 'Concluído', 'Indeferido')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.municipal_aid_programs (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null check (category in ('Habitação', 'Ação social', 'Educação', 'Emprego')),
  description text not null,
  eligibility text not null,
  application_url text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.municipal_aid_assessments (
  id bigint generated by default as identity primary key,
  requester_id uuid not null references auth.users(id) on delete cascade,
  category text not null,
  answers jsonb not null default '{}'::jsonb,
  recommended_program_ids bigint[] not null default '{}',
  created_at timestamptz not null default now()
);

create table if not exists public.municipal_budget_lines (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  area text not null,
  budgeted numeric(14,2) not null check (budgeted >= 0),
  executed numeric(14,2) not null default 0 check (executed >= 0),
  updated_at timestamptz not null default now(),
  unique (year, area)
);

alter table public.municipal_occurrences enable row level security;
alter table public.municipal_requests enable row level security;
alter table public.municipal_aid_programs enable row level security;
alter table public.municipal_aid_assessments enable row level security;
alter table public.municipal_budget_lines enable row level security;

create policy "citizens read own occurrences" on public.municipal_occurrences for select
  using (reporter_id = auth.uid() or public.is_admin());
create policy "authenticated citizens create occurrences" on public.municipal_occurrences for insert
  with check (reporter_id = auth.uid());
create policy "municipal staff manage occurrences" on public.municipal_occurrences for update
  using (public.is_admin()) with check (public.is_admin());

create policy "citizens read own requests" on public.municipal_requests for select
  using (requester_id = auth.uid() or public.is_admin());
create policy "citizens create requests" on public.municipal_requests for insert
  with check (requester_id = auth.uid());
create policy "municipal staff manage requests" on public.municipal_requests for update
  using (public.is_admin()) with check (public.is_admin());

create policy "public reads active aid programs" on public.municipal_aid_programs for select
  using (active = true or public.is_admin());
create policy "municipal staff manage aid programs" on public.municipal_aid_programs for all
  using (public.is_admin()) with check (public.is_admin());

create policy "citizens manage own assessments" on public.municipal_aid_assessments for all
  using (requester_id = auth.uid() or public.is_admin())
  with check (requester_id = auth.uid() or public.is_admin());

create policy "public reads budget lines" on public.municipal_budget_lines for select
  using (true);
create policy "municipal staff manage budget lines" on public.municipal_budget_lines for all
  using (public.is_admin()) with check (public.is_admin());

create index if not exists municipal_occurrences_status_idx on public.municipal_occurrences(status);
create index if not exists municipal_occurrences_reporter_idx on public.municipal_occurrences(reporter_id);
create index if not exists municipal_requests_requester_idx on public.municipal_requests(requester_id);
create index if not exists municipal_budget_year_idx on public.municipal_budget_lines(year);

insert into storage.buckets (id, name, public)
values ('municipal-occurrence-photos', 'municipal-occurrence-photos', false)
on conflict (id) do nothing;

create policy "citizens upload own occurrence photos"
on storage.objects for insert to authenticated
with check (bucket_id = 'municipal-occurrence-photos' and (storage.foldername(name))[1] = auth.uid()::text);

create policy "citizens read own occurrence photos"
on storage.objects for select to authenticated
using (bucket_id = 'municipal-occurrence-photos' and (storage.foldername(name))[1] = auth.uid()::text);

create policy "municipal staff read occurrence photos"
on storage.objects for select to authenticated
using (bucket_id = 'municipal-occurrence-photos' and public.is_admin());

